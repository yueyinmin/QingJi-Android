package com.qingji.app.domain

/**
 * ============================================================
 * 给食物配一个图标
 * ------------------------------------------------------------
 * 不用图片资源的原因：食物库里 100 多条，一条一张图能撑爆包体积
 * （PRD 红线 25MB）。用 emoji 按类别配，零体积、任意分辨率不糊。
 *
 * 匹配规则：按顺序看关键词，先命中的赢。
 * 顺序很重要——「牛肉面」要算面不算肉，「鸡蛋饼」要算饼。
 * ============================================================
 */
object FoodIcon {

    /** 一个分类：关键词 + 图标。 */
    private data class Rule(val keywords: List<String>, val emoji: String)

    private val rules = listOf(
        // 先判「面/粉/粥」这类带主食又有配料的复合词
        Rule(listOf("面", "粉", "米线", "馄饨", "云吞", "拉面", "意面"), "🍜"),
        Rule(listOf("粥", "稀饭", "羹"), "🥣"),
        Rule(listOf("米", "饭", "寿司"), "🍚"),
        Rule(listOf("包", "饺", "馒头", "花卷", "烧麦"), "🥟"),
        Rule(listOf("饼", "油条", "面包", "吐司", "糕", "馍"), "🥖"),
        Rule(listOf("薯", "土豆", "玉米", "山药", "红薯", "紫薯"), "🍠"),
        // 蛋白类
        Rule(listOf("蛋"), "🥚"),
        Rule(listOf("牛奶", "酸奶", "奶", "芝士", "奶酪"), "🥛"),
        Rule(listOf("豆浆", "豆腐", "豆干", "腐竹", "豆皮"), "🫘"),
        Rule(listOf("鱼", "虾", "蟹", "贝", "蛤", "鱿鱼", "三文鱼"), "🐟"),
        Rule(listOf("鸡", "鸭", "鹅"), "🍗"),
        Rule(listOf("牛", "猪", "羊", "肉", "排骨", "火腿", "培根", "香肠"), "🍖"),
        // 蔬果
        Rule(listOf("菜", "青", "菠菜", "白菜", "生菜", "西兰花", "番茄", "西红柿", "黄瓜", "茄子", "萝卜", "蘑菇", "菌", "笋"), "🥬"),
        Rule(listOf("苹果", "梨", "桃", "橙", "橘", "柚", "莓", "葡萄", "樱桃", "芒果", "火龙果", "猕猴桃"), "🍎"),
        Rule(listOf("香蕉"), "🍌"),
        Rule(listOf("西瓜", "哈密瓜", "甜瓜"), "🍉"),
        Rule(listOf("柠", "酸"), "🍋"),
        // 饮品与零食
        Rule(listOf("咖啡", "拿铁", "美式", "茶"), "☕"),
        Rule(listOf("可乐", "汽水", "雪碧", "果汁", "饮料", "奶茶"), "🥤"),
        Rule(listOf("酒", "啤", "红酒", "白酒"), "🍺"),
        Rule(listOf("坚果", "花生", "核桃", "杏仁", "腰果", "瓜子"), "🥜"),
        Rule(listOf("薯片", "饼干", "巧克力", "糖", "蛋糕", "冰淇淋", "雪糕", "布丁"), "🍪"),
        Rule(listOf("油", "黄油", "奶油"), "🧈"),
        Rule(listOf("汤", "煲"), "🍲"),
        Rule(listOf("沙拉"), "🥗")
    )

    /** 取一个图标；认不出来的给一个通用的餐具。 */
    fun emoji(name: String): String {
        val text = name.trim()
        if (text.isEmpty()) return "🍽"
        rules.forEach { rule ->
            if (rule.keywords.any { text.contains(it) }) return rule.emoji
        }
        return "🍽"
    }
}
